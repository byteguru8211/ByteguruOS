# Автозапуск сеанса ByteguruOS: консоль tty1 после автологина поднимает стол.
#
# Именно /etc/profile.d, а не ~/.bash_profile отдельного пользователя:
#   * /etc/profile исполняется раньше любого личного файла и не зависит от
#     имени вошедшего, поэтому установщику не нужно угадывать домашний
#     каталог — механизм один и для live-образа, и для установленной системы;
#   * личного файла, который надо не забыть создать, больше нет.
#
# Проверка tty обязательна: без неё любой `ssh`, `su -` или вход на tty2
# попытались бы запустить композитор из не-консольного шелла, и человек
# получил бы вместо оболочки ошибку про DRM.
if [ "$(id -u)" != "0" ] && [ "$(tty)" = "/dev/tty1" ] && \
   command -v bgwl-session >/dev/null 2>&1; then
	exec bgwl-session
fi
